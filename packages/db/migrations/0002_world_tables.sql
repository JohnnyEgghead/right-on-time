-- P2-SCHEMA. Every `world` table of SPECIFICATIONS section 3, in the document's order. Forward-only (SD-40).
-- Columns are NOT NULL unless section 3's Type says null. Foreign keys are added in 0004 (so table order is free),
-- indexes in 0005. Every time column is timestamptz, date or time; its zone is in the row (`zone`) or declared in
-- packages/db/src/zone-registry.ts (invariant 4), and no time column defaults to a database clock (SD-10).

CREATE TABLE world.branch (
  id            text PRIMARY KEY,
  name_key      text NOT NULL,
  zone          text NOT NULL,
  office_phone  text NOT NULL,
  depot_lon     double precision NOT NULL,
  depot_lat     double precision NOT NULL,
  map_file      text NOT NULL
);

