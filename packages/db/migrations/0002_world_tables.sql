  version                integer NOT NULL,  -- D15: integer version, conditional update
  planned_arrival        timestamptz,
  expected_minutes       integer NOT NULL,
  texted_arrival         timestamptz,
  late_text_sent_at      timestamptz,
  late_text_was_arrival  timestamptz,
  on_the_way_at          timestamptz,
  arrived_at             timestamptz,
  ended_at               timestamptz,
  confirmed_at           timestamptz,
  booked_via             text NOT NULL,
  booked_at              timestamptz NOT NULL,
  booked_by              uuid,
  labor_minutes          integer,
  no_parts_used          boolean NOT NULL DEFAULT false,
  billing_state          text NOT NULL,
  autopilot              boolean NOT NULL,
